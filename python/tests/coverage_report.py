def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="run the matrix and compare with the record")
    mode.add_argument("--render", action="store_true", help="rewrite the pages from the record, no run")
    args = parser.parse_args(argv)

    if args.render:
        write_pages(load_record())
        print(f"rendered {COVERAGE_MD} and {ARROW_FUNCTIONS_MD} from {RECORD}")
        return 0

    problem = default_matrix_problem()
    if problem:
        print(f"coverage_report: {problem}", file=sys.stderr)
        return 2
    import differential_report
    cells, ops, types, total, elapsed = differential_report.run(quiet=True)
    record = make_record(cells)
    t = totals(record)
    print(f"total: {t[0]} cases  |  pass {t[1]}  documented {t[2]}  unclassified {t[3]}  skip {t[4]}  |  "
          f"{elapsed:.1f}s")
    if args.check:
        diffs = compare_cells(record["cells"], load_record()["cells"])
        print("coverage table: " + ("matches the record" if not diffs else f"STALE in {len(diffs)} cell(s)"))
        for line in diffs[:40]:
            print("  " + line)
        return 1 if diffs else 0
    if t[3]:
        print("coverage_report: unclassified divergences; run differential_report.py and classify them first",
              file=sys.stderr)
        return 1
    os.makedirs(os.path.dirname(RECORD), exist_ok=True)
    with open(RECORD, "w") as fh:
        fh.write(dump_record(record))
    write_pages(record)
    print(f"wrote {RECORD}, {COVERAGE_MD} and {ARROW_FUNCTIONS_MD}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
