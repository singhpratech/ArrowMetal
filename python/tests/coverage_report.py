# the record: one row per (operation, type) cell

FIELDS = ("operation", "type", "cases", "pass", "documented", "unclassified", "skipped")


def cells_from_report(cells):
    """differential_report.run()'s {(op, type): Cell} -> sorted record rows (lists, FIELDS order)."""
    rows = []
    for (op_name, type_name), c in cells.items():
        documented = c.failed - c.new
        rows.append([op_name, type_name, c.total, c.passed, documented, c.new, c.skipped])
    return sorted(rows, key=lambda r: (r[0], r[1]))


def run_conditions():
    import pyarrow as pa
    import arrowmetal as am
    return OrderedDict([("arrowmetal", am.__version__), ("pyarrow", pa.__version__),
                        ("device", am.device_name()), ("router", am.get_router())])


def default_matrix_problem():
    """Why the current process is not running the default matrix, or None."""
    for var in ("DIFF_QUICK", "DIFF_LARGE"):
        if os.environ.get(var) == "1":
            return f"{var}=1 changes the datasets; the record is the default matrix"
    router = os.environ.get("ARROWMETAL_ROUTER")
    if router not in (None, "gpu"):
        return f"ARROWMETAL_ROUTER={router}; the record is the matrix with the router pinned to the GPU"
    return None


def load_record(path=RECORD):
    with open(path) as fh:
        return json.load(fh)


def dump_record(record):
    """JSON with one cell per line, so a changed cell is a one-line diff."""
    lines = ["{", '  "run": ' + json.dumps(record["run"]) + ",", '  "fields": ' + json.dumps(list(FIELDS)) + ",",
             '  "cells": [']
    cells = record["cells"]
    for i, row in enumerate(cells):
        lines.append("    " + json.dumps(row) + ("," if i + 1 < len(cells) else ""))
    lines += ["  ]", "}", ""]
    return "\n".join(lines)


def make_record(cells):
    return {"run": run_conditions(), "fields": list(FIELDS), "cells": cells_from_report(cells)}


def compare_cells(fresh_rows, recorded_rows):
    """Differences between two lists of record rows, as readable lines (empty when equal)."""
    a = {(r[0], r[1]): r for r in fresh_rows}
    b = {(r[0], r[1]): r for r in recorded_rows}
    out = []
    for key in sorted(set(a) | set(b)):
        if key not in b:
            out.append(f"{key[0]} / {key[1]}: in this run, not in the record")
        elif key not in a:
            out.append(f"{key[0]} / {key[1]}: in the record, not in this run")
        elif a[key] != b[key]:
            fields = ", ".join(f"{name} {b[key][i]} -> {a[key][i]}" for i, name in enumerate(FIELDS)
                               if i >= 2 and a[key][i] != b[key][i])
            out.append(f"{key[0]} / {key[1]}: {fields}")
    return out


# ---------------------------------------------------------------------------------------------------
# aggregation and rendering

def _registry():
    from arrowmetal import functions as F
    return F


def per_operation(record):
    """{op: [cases, pass, documented, unclassified, skipped]} over the record's cells."""
    out = OrderedDict()
    for row in record["cells"]:
        t = out.setdefault(row[0], [0, 0, 0, 0, 0])
        for i in range(5):
            t[i] += row[2 + i]
    return out


def per_function(record):
    """OrderedDict name -> {"ops": [...], "counts": [cases, pass, documented, unclassified, skipped]}
    in the registry's section order, for every Arrow name some operation counts toward."""
    F = _registry()
    ops = per_operation(record)
    by_name = {}
    for op_name, counts in ops.items():
        for name in OPERATION_FUNCTIONS.get(op_name, ()):
            entry = by_name.setdefault(name, {"ops": [], "counts": [0, 0, 0, 0, 0]})
            entry["ops"].append(op_name)
            for i in range(5):
                entry["counts"][i] += counts[i]
    out = OrderedDict()
    for section in F.SECTIONS:
        for f in F._REGISTRY.values():
            if f.section == section and f.name in by_name:
                out[f.name] = dict(by_name[f.name], section=section)
    return out


def totals(record):
    t = [0, 0, 0, 0, 0]
    for counts in per_operation(record).values():
        for i in range(5):
            t[i] += counts[i]
    return t


def _n(x):
    return f"{x:,}"


def _matrix_shape(record):
    ops = {r[0] for r in record["cells"]}
    types = {r[1] for r in record["cells"]}
    cases = sorted({r[2] for r in record["cells"]})
    return len(ops), len(types), len(record["cells"]), cases


def coverage_section(record):
    """The block between BEGIN and END in docs/COVERAGE.md."""
    F = _registry()
    run = record["run"]
    n_ops, n_types, n_cells, per_cell = _matrix_shape(record)
    cases, passed, documented, unclassified, skipped = totals(record)
    functions = per_function(record)
    ops = per_operation(record)
    outside = [o for o in ops if o in OUTSIDE]
    out = [BEGIN, "",
           f"The differential matrix (`python/tests/test_differential.py`, [TESTING.md](TESTING.md#3-the-differential-matrix)) "
           f"runs {n_ops} operations over {n_types} column types: {_n(n_cells)} (operation, type) cells, each over "
           f"{' / '.join(str(c) for c in per_cell)} datasets, {_n(cases)} cases. The run recorded in "
           f"`docs/data/differential_coverage.json` (ArrowMetal {run['arrowmetal']}, pyarrow {run['pyarrow']}, "
           f"{run['device']}, router `{run['router']}`): **{_n(passed)} pass, {_n(documented)} documented "
           f"divergences, {_n(skipped)} skipped, {_n(unclassified)} unclassified**.",
           "",
           "A case counts toward an Arrow function when the ArrowMetal call it runs is that function's "
           "implementation (the call column of [ARROW_FUNCTIONS.md](ARROW_FUNCTIONS.md)) or, for an ArrowMetal "
           "call with no Arrow name of its own (`sort`, `argsort`, `to_strings`), when its answer is compared "
           "with that function's result. One case can check several functions — a `compare_scalar` case runs "
           "all six comparisons — so the rows below add up to more than the case total. A documented "
           "divergence is a failing case that matches an open finding in [EVALUATION.md](EVALUATION.md); a "
           "skipped case is an operation that does not implement that column type.",
           "",
           f"{len(functions)} of the {len(F.list_functions())} Arrow function names have matrix cases. Every "
           "name, with or without them, is also run through `call_function` against `pyarrow.compute` in "
           "`python/tests/test_functions.py`.",
           "",
           "| Arrow function | Section | Matrix operations | Cases | Pass | Documented | Skipped |",
           "|---|---|---|---:|---:|---:|---:|"]
    for name, entry in functions.items():
        c = entry["counts"]
        out.append(f"| `{name}` | {entry['section']} | {', '.join(f'`{o}`' for o in entry['ops'])} | "
                   f"{_n(c[0])} | {_n(c[1])} | {_n(c[2])} | {_n(c[4])} |")
    out += ["",
            f"The {len(outside)} operations that check no Arrow compute function, with what they check:",
            "",
            "| Matrix operation | What it checks | Cases | Pass | Documented | Skipped |",
            "|---|---|---:|---:|---:|---:|"]
    for o in outside:
        c = ops[o]
        out.append(f"| `{o}` | {OUTSIDE[o]} | {_n(c[0])} | {_n(c[1])} | {_n(c[2])} | {_n(c[4])} |")
    out += ["", f"Regenerate with `{COMMAND}` (runs the matrix); `--check` compares a fresh run with the "
                "record and writes nothing.", "", END]
    return "\n".join(out)


def arrow_functions_section(record):
    """The per-section summary docs/ARROW_FUNCTIONS.md carries (function_table_report.py --page)."""
    F = _registry()
    functions = per_function(record)
    cases, passed, documented, unclassified, skipped = totals(record)
    out = ["## Differential matrix cases, by section", "",
           f"Separately from the row-by-row calls above, `python/tests/test_differential.py` runs every "
           f"ArrowMetal operation over generated columns of every type it accepts: {_n(cases)} cases in the "
           f"recorded run, {_n(passed)} pass, {_n(documented)} documented divergences, {_n(skipped)} skipped, "
           f"{_n(unclassified)} unclassified. [COVERAGE.md](COVERAGE.md#differential-cases-per-arrow-function) "
           "has the count for each name; this is how many names in each section the matrix reaches.",
           "",
           "| Section | Names | With matrix cases | Names without |",
           "|---|---:|---:|---|"]
    for section in F.SECTIONS:
        names = [f.name for f in F._REGISTRY.values() if f.section == section]
        reached = [n for n in names if n in functions]
        missing = [n for n in names if n not in functions]
        out.append(f"| {section} | {len(names)} | {len(reached)} | "
                   f"{', '.join(f'`{n}`' for n in missing) or '-'} |")
    total = len(F.list_functions())
    out.append(f"| **Total** | **{total}** | **{len(functions)}** | |")
    return "\n".join(out)


def replace_block(text, block):
    start, stop = text.find(BEGIN), text.find(END)
    if start < 0 or stop < 0:
        raise SystemExit(f"{COVERAGE_MD} has no {BEGIN} ... {END} block")
    return text[:start] + block + text[stop + len(END):]


def render_pages(record):
    """{path: content} for the two generated pages."""
    import function_table_report
    with open(COVERAGE_MD) as fh:
        coverage = replace_block(fh.read(), coverage_section(record))
    return {COVERAGE_MD: coverage, ARROW_FUNCTIONS_MD: function_table_report.page(record) + "\n"}


def write_pages(record):
    for path, content in render_pages(record).items():
        with open(path, "w") as fh:
            fh.write(content)


